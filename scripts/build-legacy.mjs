// Builds the old board page for the Worker (#C723 A1): page/board.template.html + the team's board.config.json, written as a
// module (worker/legacy-page.generated.mjs, git-ignored: the config never enters this repository). board-entry.mjs imports it
// when it exists. Usage: node scripts/build-legacy.mjs <board.config.json> [out.mjs]
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { buildChecked, headCommit } from "./build-page.mjs";

export function legacyModule(html) {
  return `// Generated by scripts/build-legacy.mjs. Do not edit, do not commit.\nexport default ${JSON.stringify(html)};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const [configPath, out = fileURLToPath(new URL("../worker/legacy-page.generated.mjs", import.meta.url))] = process.argv.slice(2);
  if (!configPath) { console.error("Usage: node scripts/build-legacy.mjs <board.config.json> [out.mjs]"); process.exit(2); }
  try {
    const html = buildChecked(readFileSync(new URL("../page/board.template.html", import.meta.url), "utf8"), JSON.parse(readFileSync(configPath, "utf8")), undefined, { commit: headCommit(), pack: process.env.BOARD_PACK });
    writeFileSync(out, legacyModule(html));
    console.log(`Built ${out}`);
  } catch (e) { console.error(e.message); process.exit(1); }
}
