// The board's icon (#C1055, option F, the attitude indicator; the owner's pick). Source files live in page/icon/; this writes what the page and the
// Worker carry from them, so the two never differ from the files (tests/board-icon.test.mjs fails if they do):
//   page/board.template.html   the icon links between <!--ICONS--> and <!--END_ICONS--> in the page head: data: links, no request to another host;
//                              the page has no manifest of its own (the store page's is the Worker's, tests/owner-phone-push.test.mjs);
//   worker/board-icons.mjs     the 192 and 512 px pictures as data: links, for the Worker's /manifest.webmanifest.
// Usage: node scripts/build-icons.mjs        (run after a file in page/icon/ changes)
import { readFileSync, writeFileSync, realpathSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROOT = new URL("../", import.meta.url);
const file = (n) => readFileSync(new URL(`page/icon/${n}`, ROOT));
const png = (n) => `data:image/png;base64,${file(n).toString("base64")}`;
export const svgUri = () => `data:image/svg+xml,${encodeURIComponent(file("board-icon.svg").toString("utf8").replace(/\s*\n\s*/g, ""))}`;

export function iconLinks() {
  return [
    "<!--ICONS-->",
    `<link rel="icon" type="image/svg+xml" href="${svgUri()}">`,
    `<link rel="icon" type="image/png" sizes="192x192" href="${png("icon-192.png")}">`,
    `<link rel="apple-touch-icon" sizes="180x180" href="${png("apple-touch-icon.png")}">`,
    "<!--END_ICONS-->",
  ].join("\n");
}

export function iconsModule() {
  return `// Generated by scripts/build-icons.mjs from page/icon/ (#C1055): do not edit by hand.\nexport const ICON_192 = ${JSON.stringify(png("icon-192.png"))};\nexport const ICON_512 = ${JSON.stringify(png("icon-512.png"))};\n`;
}

const BLOCK = /<!--ICONS-->[\s\S]*?<!--END_ICONS-->/;
export function withIcons(template) {
  if (BLOCK.test(template)) return template.replace(BLOCK, () => iconLinks());
  const at = "<title>{{TITLE}}</title>\n";
  if (!template.includes(at)) throw new Error("the template has no <title>{{TITLE}}</title> line to put the icons after");
  return template.replace(at, () => `${at}${iconLinks()}\n`);
}

if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  const page = new URL("page/board.template.html", ROOT);
  writeFileSync(page, withIcons(readFileSync(page, "utf8")));
  writeFileSync(new URL("worker/board-icons.mjs", ROOT), iconsModule());
  console.log("icons written: page/board.template.html and worker/board-icons.mjs");
}
